"""IDAPython: export the Hex-Rays closure of one native dispatch table.

Run inside IDA on the BGI.exe database:

    SEL_TABLE=0x505B00 SEL_GROUP=D0 SEL_OUT=src/raw/bgi1622/d0.c \
        idat -A -S"src/tools/ida_export_closure.py" bgi.i64

SEL_SLOTS may restrict the roots to comma-separated hexadecimal selectors
(for example SEL_SLOTS=18,19,1A,1D). SEL_ROOTS adds hexadecimal function
addresses, for virtual callees recovered outside the direct-call closure.
SEL_TABLES may instead supply a comma-separated GROUP:ADDRESS list, exporting
one deduplicated closure for all tables (SEL_TABLE is then not required).

Starting from every non-null slot of the 0x400-byte table it walks direct
calls, functions taken by address (callbacks, thread entries) and vtables
referenced from code (runs of code pointers), so virtual methods are part of
the export.  The walk stops at library functions and at the VM operand helpers every handler shares
(they are documented in src/engine/cthread.c).

Output: one `//==== ADDR name size=N` block per function, ordered by
address, pseudocode verbatim; failures keep the disassembly.  With SEL_ASM
set, the disassembly of the same functions goes to that file (Hex-Rays loses
__usercall register arguments and x87 stack order; the asm settles them).  The header
lists the selector -> handler map.  The file is lossless and is never edited
by hand; cleaned code goes to src/engine/.
"""
import os

import ida_auto
import ida_bytes
import ida_funcs
import ida_hexrays
import ida_name
import ida_pro
import ida_segment
import idautils
import idc

GROUP = os.environ.get("SEL_GROUP", "??")
TABLES = ([(group, int(address, 16)) for group, address in
           (item.split(":") for item in os.environ["SEL_TABLES"].split(","))]
          if os.environ.get("SEL_TABLES") else [(GROUP, int(os.environ["SEL_TABLE"], 16))])
OUT = os.environ["SEL_OUT"]
# CThread pop int / pop pointer / push / script error; cthread.c covers them.
STOP = {0x445480, 0x48EA40, 0x4454A0, 0x464C50}
VTABLES = set()  # vtables referenced from closure code


def is_code_ptr(value):
    seg = ida_segment.getseg(value)
    return bool(seg and seg.perm & ida_segment.SEGPERM_EXEC and ida_funcs.get_func(value)
                and ida_funcs.get_func(value).start_ea == value)


def vtable_entries(addr):
    entries = []
    while is_code_ptr(ida_bytes.get_dword(addr)):
        entries.append(ida_bytes.get_dword(addr))
        addr += 4
    return entries


def successors(fn):
    out = set()
    for head in idautils.FuncItems(fn.start_ea):
        for ref in idautils.CodeRefsFrom(head, False):
            callee = ida_funcs.get_func(ref)
            if callee and callee.start_ea == ref:
                out.add(ref)
        for ref in idautils.DataRefsFrom(head):
            seg = ida_segment.getseg(ref)
            if is_code_ptr(ref):
                out.add(ref)  # callback / thread entry passed by address
            elif seg and not seg.perm & ida_segment.SEGPERM_EXEC:
                entries = vtable_entries(ref)
                if entries:
                    VTABLES.add(ref)
                    out.update(entries)
    return out


def main():
    ida_auto.auto_wait()
    ida_hexrays.init_hexrays_plugin()
    handlers = []
    slots = [int(s, 16) for s in os.environ["SEL_SLOTS"].split(",")] if os.environ.get("SEL_SLOTS") else range(256)
    for group, table in TABLES:
        for slot in slots:
            target = ida_bytes.get_dword(table + slot * 4)
            if target:
                handlers.append((group, slot, target))
    roots = [int(s, 16) for s in os.environ.get("SEL_ROOTS", "").split(",") if s]
    seen, queue = set(), [t for _, _, t in handlers] + roots
    while queue:
        ea = queue.pop()
        if ea in seen or ea in STOP:
            continue
        fn = ida_funcs.get_func(ea)
        if not fn or fn.flags & ida_funcs.FUNC_LIB:
            continue
        seen.add(ea)
        queue.extend(successors(fn))

    with open(OUT, "w", encoding="utf-8") as out:
        if len(TABLES) == 1:
            group, table = TABLES[0]
            out.write(f"// Hex-Rays export of the 0x{group} native table at 0x{table:X} and its closure.\n")
        else:
            out.write("// Hex-Rays export of the native tables and their deduplicated closure.\n")
            for group, table in TABLES:
                out.write(f"// Table 0x{group} at 0x{table:X}.\n")
        out.write("// Generated by src/tools/ida_export_closure.py; never edit.\n")
        out.write("// Selector -> handler:\n")
        for group, slot, target in handlers:
            out.write(f"//   {group}:{slot:02X} -> {target:06X}\n")
        for root in roots:
            out.write(f"// Additional virtual/callback root: {root:06X}\n")
        out.write(f"// {len(seen)} functions.\n\n")
        for ea in sorted(seen):
            fn = ida_funcs.get_func(ea)
            name = ida_name.get_short_name(ea)
            out.write(f"//==== {ea:06X} {name} size={fn.end_ea - fn.start_ea}\n")
            try:
                out.write(str(ida_hexrays.decompile(ea)))
            except Exception as exc:  # keep the disassembly when Hex-Rays fails
                out.write(f"// decompilation failed: {exc}\n")
                for head in idautils.FuncItems(ea):
                    out.write(f"// {head:06X}  {idc.GetDisasm(head)}\n")
            out.write("\n\n")

    if os.environ.get("SEL_ASM"):
        with open(os.environ["SEL_ASM"], "w", encoding="utf-8") as out:
            for ea in sorted(VTABLES):
                name = ida_name.get_name(ea)
                out.write(f";vtable {ea:06X} {ida_name.demangle_name(name, 0) or name}\n")
                for i, e in enumerate(vtable_entries(ea)):
                    out.write(f";   +{i * 4:02X} {e:06X} {ida_name.get_short_name(e)}\n")
            out.write("\n")
            for ea in sorted(seen):
                out.write(f";==== {ea:06X} {ida_name.get_short_name(ea)}\n")
                for head in idautils.FuncItems(ea):
                    out.write(f"{head:06X}  {idc.GetDisasm(head)}\n")
                out.write("\n")


main()
ida_pro.qexit(0)

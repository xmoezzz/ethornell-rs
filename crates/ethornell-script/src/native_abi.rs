pub fn lookup(group: u8, id: u16) -> Option<NativeCallAbi> {
    let table = match group {
        0x80 => &GROUP_80,
        0x81 => &GROUP_81,
        0x90 => &GROUP_90,
        0x91 => &GROUP_91,
        0x92 => &GROUP_92,
        0xA0 => &GROUP_A0,
        0xB0 => &GROUP_B0,
        0xC0 => &GROUP_C0,
        _ => return None,
    };
    let packed = *table.get(id as usize)?;
    if packed & 0x8000 == 0 {
        return None;
    }
    let raw_descriptor_bit8 = packed & 0x0100 != 0;
    let procedure = installs_procedure(group, id);
    let stack_outputs = if (group, id) == (0x80, 0x5A) {
        // sub_489160 pushes `(remaining_time != 0)` immediately even though a
        // positive value also installs CProcWaitTiming.
        1
    } else if procedure {
        0
    } else {
        match (group, id) {
            // Native handlers that call the BP operand push helper more than
            // once on their successful path.
            (0x80, 0x08) | (0x80, 0x0D) | (0x90, 0xD7) | (0xB0, 0x17) => 2,
            (0x80, 0x80) | (0x91, 0x8D) => 3,
            _ => usize::from(raw_descriptor_bit8),
        }
    };
    Some(NativeCallAbi {
        argc: (packed & 0x00FF) as usize,
        stack_outputs,
        installs_procedure: procedure,
        raw_descriptor_bit8,
    })
}

pub fn generic_name(group: u8, id: u16) -> Option<&'static str> {
    lookup(group, id)?;
    Some(match group {
        0x80 | 0x81 => "NativeSystemCall",
        0x90..=0x92 => "NativeGraphCall",
        0xA0 => "NativeSoundCall",
        0xB0 | 0xC0 => "NativeUserCall",
        _ => return None,
    })
}

pub fn installs_procedure(group: u8, id: u16) -> bool {
    matches!(
        (group, id),
        (0x81, 0x30)
            | (0x81, 0xF2)
            | (0x80, 0x54)
            | (0x80, 0x5A)
            | (0x80, 0x5C)
            | (0x80, 0xB4)
            | (0x80, 0xC0)
            | (0x80, 0xC4)
            | (0x80, 0xCF)
            | (0xA0, 0x20)
            | (0xA0, 0x21)
            | (0xA0, 0x23)
            | (0xA0, 0x27)
            | (0xA0, 0x28)
            | (0x92, 0x14)
            | (0x92, 0xF1)
            | (0x90, 0x10)
            | (0x90, 0xF4)
            | (0x91, 0x90)
            | (0x91, 0x92)
            | (0xB0, 0x08)
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn contains_every_recovered_native_handler() {
        let count = [0x80, 0x81, 0x90, 0x91, 0x92, 0xA0, 0xB0, 0xC0]
            .into_iter()
            .flat_map(|group| (0..=255).map(move |id| (group, id)))
            .filter(|&(group, id)| lookup(group, id).is_some())
            .count();
        // 695 handler pointers in the eight dispatch tables; 0x81:0x21 and
        // 0x81:0xDA have descriptors but null handlers.
        assert_eq!(count, 695);
    }

    #[test]
    fn preserves_alias_based_argument_reads() {
        assert_eq!(lookup(0x80, 0x60).unwrap().argc, 3);
        assert_eq!(lookup(0x92, 0x97).unwrap().argc, 7);
        assert_eq!(lookup(0x80, 0x41).unwrap().argc, 1);
    }

    #[test]
    fn distinguishes_procedure_installation_from_stack_results() {
        assert!(!lookup(0x80, 0x5c).unwrap().returns_value());
        assert_eq!(lookup(0x80, 0x5c).unwrap().stack_outputs, 0);
        assert!(lookup(0x80, 0x5c).unwrap().installs_procedure);
        assert_eq!(lookup(0x80, 0x5a).unwrap().stack_outputs, 1);
        assert!(lookup(0x80, 0x5a).unwrap().installs_procedure);
        assert!(installs_procedure(0x80, 0x5c));
        assert!(!installs_procedure(0x90, 0x12));
    }

    #[test]
    fn input_master_gate_write_has_no_immediate_output() {
        let abi = lookup(0x80, 0x14).unwrap();
        assert_eq!(abi.argc, 1);
        assert_eq!(abi.stack_outputs, 0);
        assert!(!abi.installs_procedure);
    }
}
